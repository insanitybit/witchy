#!/usr/bin/env python3
"""Regenerate crates/witchy-types/src/std_pruning_roots.rs.

Std pruning (crates/witchy-types/src/std_pruning.rs) keeps every standard-
library function any retained item names. The compiler also reaches std
functions WITHOUT a source name -- `d[i] = v` desugars to a std insert whose
`unique` parameter decides `mode opt` acceptance -- and a pruned function
there changes what is accepted, with no fallback. Every std function the
compiler names is a string literal in its own sources, so every such literal
is a root. The witchy-types test `pruning_roots_cover_every_compiler_std_literal`
fails when this file is stale.
"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
linker = (root / "crates/witchy-syntax/src/linker.rs").read_text()
modules = re.findall(r'"(\w+)"', re.search(r"pub const STD_MODULES: &\[&str\] = &\[(.*?)\];", linker, re.S).group(1))
pattern = re.compile(r'"((?:%s)\.[A-Za-z_][A-Za-z0-9_]*)"' % "|".join(modules))
names = set()
for crate in ["crates/witchy-types", "crates/witchy-lower", "crates/witchy-syntax",
              "crates/witchy-wir", "crates/witchy-interp", "crates/witchy-runtime", "src"]:
    for path in sorted((root / crate).rglob("*.rs")):
        if path.name in ("std_pruning_roots.rs", "std_pruning.rs"):
            continue
        names.update(pattern.findall(path.read_text(errors="replace")))
out = ["// @generated by scripts/gen-std-pruning-roots.py -- do not edit.",
       "/// Every standard-library function name the compiler spells as a literal.",
       "pub const COMPILER_STD_NAMES: &[&str] = &["]
out += [f'    "{name}",' for name in sorted(names)]
out += ["];", ""]
target = root / "crates/witchy-types/src/std_pruning_roots.rs"
text = "\n".join(out)
if "--check" in sys.argv:
    sys.exit(0 if target.exists() and target.read_text() == text else 1)
target.write_text(text)
print(f"{len(names)} names -> {target.relative_to(root)}")
