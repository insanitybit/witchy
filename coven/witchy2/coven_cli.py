"""Command-line arguments for Coven registry and release operations."""

import argparse
from pathlib import Path


def tuf_mirror_options(client, *, fetching=False):
    client.add_argument("--registry", required=True)
    client.add_argument("--id", required=True)
    client.add_argument("--root", required=True, type=Path)
    client.add_argument("--root-pin", required=True)
    client.add_argument("--trust", required=True, type=Path)
    client.add_argument("--trust-pin", required=True)
    client.add_argument("--ca-file", type=Path, help="PEM CA bundle for the HTTPS mirror")
    client.add_argument("--ca-pin", help="SHA-384 pin for the selected or default PEM CA bundle")
    for worker in ("selector", "download", "extractor") if fetching else ("selector", "download"):
        client.add_argument(f"--{worker}-module", type=Path, help=f"prebuilt Witchy {worker} worker")
        client.add_argument(f"--{worker}-pin", help=f"independently provisioned SHA-384 pin for --{worker}-module")


def package_inputs(commands):
    pack = commands.add_parser("pack", help="write a library's canonical release payload to stdout")
    pack.add_argument("package", type=Path)
    pack.add_argument("--manifest-pin", help="SHA-384 pin of the absolute, resolved manifest path passed as package")
    inspect = commands.add_parser("inspect", help="show a packed release's coordinates, dependencies and content digest")
    inspect.add_argument("release", type=Path)
    stage = commands.add_parser("stage", help="privately stage a packed candidate by content digest")
    stage.add_argument("bundle", type=Path)
    stage.add_argument("--staging-dir", required=True, type=Path)
    stage.add_argument("--module", type=Path)
    stage.add_argument("--module-pin")


def ci_commands(commands):
    ci = commands.add_parser("ci", help="stage and retrieve receipts with an enrolled CI identity")
    ci_actions = ci.add_subparsers(dest="action", required=True)
    ci_stage = ci_actions.add_parser("stage", help="upload a candidate using an OIDC token on standard input")
    ci_stage.add_argument("bundle", type=Path)
    ci_receipt = ci_actions.add_parser("receipt", help="retrieve this CI job's receipt with a fresh OIDC token")
    ci_receipt.add_argument("package")
    ci_receipt.add_argument("digest")
    for action in (ci_stage, ci_receipt):
        action.add_argument("--origin", required=True)
        action.add_argument("--ca-file", type=Path, help="PEM CA bundle for this HTTPS origin")
        action.add_argument("--ca-pin", help="independently provisioned SHA-384 pin for the selected PEM bundle")
        action.add_argument("--key", required=True, type=Path)
        action.add_argument("--transport-module", type=Path, help="prebuilt Witchy HTTPS worker")
        action.add_argument("--transport-pin", help="independently provisioned SHA-384 pin for --transport-module")
    ci_public = ci_actions.add_parser("public-key", help="print the ML-DSA-87 public key for enrollment")
    ci_public.add_argument("--key", required=True, type=Path)
    for action in (ci_public, ci_stage, ci_receipt):
        action.add_argument("--signer-module", type=Path, help="prebuilt Witchy runner signer")
        action.add_argument("--signer-pin", help="independently provisioned SHA-384 pin for --signer-module")
    ci_serve = ci_actions.add_parser("serve", help="serve private CI staging over Witchy HTTPS")
    ci_serve.add_argument("--listen", required=True)
    ci_serve.add_argument("--chain", required=True, type=Path)
    ci_serve.add_argument("--tls-key", required=True, type=Path)
    ci_serve.add_argument("--module", required=True, type=Path)
    ci_serve.add_argument("--module-pin", required=True)
    ci_serve.add_argument("--storage-module", required=True, type=Path)
    ci_serve.add_argument("--storage-pin", required=True)


def release_commands(commands):
    release = commands.add_parser("release", help="operate the private maintainer approval store")
    actions = release.add_subparsers(dest="action", required=True)
    init = actions.add_parser("init", help="provision the private staging tables")
    init.add_argument("--staging-dir", required=True, type=Path)
    init.add_argument("--module", type=Path)
    init.add_argument("--module-pin")
    backup = actions.add_parser("backup", help="snapshot the private staging store")
    backup.add_argument("--staging-dir", required=True, type=Path)
    backup.add_argument("--out", required=True, type=Path)
    restore = actions.add_parser("restore", help="verify a pinned backup and recover it into a new directory")
    restore.add_argument("--staging-dir", required=True, type=Path)
    restore.add_argument("--backup", required=True, type=Path)
    restore.add_argument("--backup-pin", required=True)
    for recovery in (backup, restore):
        for name in ("manifest", "database"):
            recovery.add_argument(f"--{name}-module", type=Path)
            recovery.add_argument(f"--{name}-pin")
    review_serve = actions.add_parser("review-serve", help="serve maintainer review over Witchy HTTPS")
    for name in ("staging-dir", "mirror", "trust", "root", "chain", "tls-key", "module", "inspect-module", "challenge-module", "commit-module", "baseline-module"):
        review_serve.add_argument("--" + name, required=True, type=Path)
    for name in ("trust-pin", "root-pin", "listen", "module-pin", "inspect-pin", "challenge-pin", "commit-pin", "baseline-pin"):
        review_serve.add_argument("--" + name, required=True)
    enroll_start = actions.add_parser("enroll-start", help="issue a scoped maintainer enrollment request")
    enroll_start.add_argument("--staging-dir", required=True, type=Path)
    enroll_start.add_argument("--package", required=True, action="append")
    enroll_start.add_argument("--replace", help="credential ID to replace with the same package scope")
    enroll_finish = actions.add_parser("enroll-finish", help="verify possession and install the enrolled credential")
    enroll_finish.add_argument("--staging-dir", required=True, type=Path)
    enroll_finish.add_argument("response", type=Path)
    local_review_actions = [enroll_start, enroll_finish]
    challenge_actions = [enroll_start]
    for name, label in (("set-policy", "install an independently provisioned approval policy"),
                        ("review-url", "print the configured HTTPS browser review URL for a candidate"),
                        ("challenge", "prepare a WebAuthn challenge for a staged digest"),
                        ("approve", "verify a maintainer assertion and record approval"),
                        ("receipt", "retrieve recorded evidence for a staged digest")):
        action = actions.add_parser(name, help=label)
        action.add_argument("--staging-dir", required=True, type=Path)
        if name == "set-policy":
            action.add_argument("policy", type=Path)
        elif name == "approve":
            action.add_argument("challenge")
            action.add_argument("assertion", type=Path)
        else:
            action.add_argument("digest")
        local_review_actions.append(action)
        if name == "challenge":
            challenge_actions.append(action)
    for action in local_review_actions:
        action.add_argument("--module", type=Path, help="prebuilt Witchy worker")
        action.add_argument("--module-pin", help="independently provisioned SHA-384 pin for --module")
    for action in challenge_actions:
        action.add_argument("--challenge-module", type=Path, help="prebuilt Witchy challenge issuer")
        action.add_argument("--challenge-pin", help="independently provisioned SHA-384 pin for --challenge-module")


def tuf_commands(commands):
    tuf = commands.add_parser("tuf", help="seal, authorize, publish, or fetch approved TUF targets")
    tuf_commands = tuf.add_subparsers(dest="action", required=True)
    rotate_policy = tuf_commands.add_parser("rotate-policy", help="prepare a release trust update retaining exact sealed bundles")
    rotate_policy.add_argument("bundles", nargs="*", type=Path)
    rotate_policy.add_argument("--trust", required=True, type=Path)
    rotate_policy.add_argument("--trust-pin", required=True)
    rotate_policy.add_argument("--policy", required=True, type=Path)
    rotate_policy.add_argument("--out", required=True, type=Path)
    sign_target = tuf_commands.add_parser("sign-package", help="sign the exact package bytes for one registry")
    sign_target.add_argument("bundle", type=Path)
    sign_target.add_argument("--registry-id", required=True)
    sign_target.add_argument("--key", required=True, type=Path)
    sign_target.add_argument("--out", required=True, type=Path)
    seal_target = tuf_commands.add_parser("seal", help="form a TUF target from a witnessed private approval")
    seal_target.add_argument("digest")
    seal_target.add_argument("--staging-dir", required=True, type=Path)
    seal_target.add_argument("--publisher-signature", required=True, type=Path)
    seal_target.add_argument("--trust", required=True, type=Path)
    seal_target.add_argument("--witness-key", required=True, type=Path)
    seal_target.add_argument("--out", required=True, type=Path)
    for action in (sign_target, seal_target):
        action.add_argument("--module", type=Path, help="prebuilt Witchy signer")
        action.add_argument("--module-pin", help="independently provisioned SHA-384 pin for --module")
    seal_target.add_argument("--snapshot-module", type=Path, help="prebuilt Witchy sealing snapshot reader")
    seal_target.add_argument("--snapshot-pin", help="independently provisioned SHA-384 pin for --snapshot-module")
    authorize = tuf_commands.add_parser("authorize", help="sign delegated metadata after verifying each release")
    authorize.add_argument("bundles", nargs="*", type=Path)
    authorize.add_argument("--role", required=True)
    authorize.add_argument("--parent", required=True, type=Path)
    authorize.add_argument("--parent-pin", required=True)
    authorize.add_argument("--trust", required=True, type=Path)
    authorize.add_argument("--trust-pin", required=True)
    authorize.add_argument("--version", required=True, type=int)
    authorize.add_argument("--valid-days", required=True, type=int)
    authorize.add_argument("--key", required=True, action="append", type=Path)
    authorize.add_argument("--out", required=True, type=Path)
    for role in ("prepare", "signer", "finalizer"):
        authorize.add_argument(f"--{role}-module", type=Path, help=f"prebuilt Witchy {role} worker")
        authorize.add_argument(f"--{role}-pin", help=f"independently provisioned SHA-384 pin for --{role}-module")
    tuf_publish = tuf_commands.add_parser("publish", help="verify and publish a presigned static mirror update")
    tuf_publish.add_argument("--incoming", required=True, type=Path)
    tuf_publish.add_argument("--mirror", required=True, type=Path)
    tuf_publish.add_argument("--root", required=True, type=Path)
    tuf_publish.add_argument("--root-pin", required=True)
    tuf_publish.add_argument("--trust", required=True, type=Path)
    tuf_publish.add_argument("--trust-pin", required=True)
    for action in (rotate_policy, tuf_publish):
        action.add_argument("--module", type=Path, help="prebuilt Witchy worker")
        action.add_argument("--module-pin", help="independently provisioned SHA-384 pin for --module")
    tuf_serve = tuf_commands.add_parser("serve", help="serve a published tree over Witchy HTTPS")
    tuf_serve.add_argument("--mirror", required=True, type=Path)
    tuf_serve.add_argument("--listen", default="127.0.0.1:8419")
    tuf_serve.add_argument("--tls-key", required=True, type=Path)
    tuf_serve.add_argument("--module", required=True, type=Path)
    tuf_serve.add_argument("--module-pin", required=True)
    tuf_serve.add_argument("--tls-ca-file", type=Path, help="PEM trust anchors for the installed mirror identity")
    tuf_serve.add_argument("--tls-ca-pin", help="independent SHA-384 pin of the mirror identity PEM trust anchors")
    tuf_serve.add_argument("--tls-check-module", type=Path, help="Wasm module that verifies the installed identity")
    tuf_serve.add_argument("--tls-check-pin", help="independent SHA-384 pin of the identity check module")
    tuf_catalog = tuf_commands.add_parser("catalog", help="list release coordinates in the verified TUF mirror")
    tuf_fetch = tuf_commands.add_parser("fetch", help="verify TUF and release evidence before writing package bytes")
    tuf_fetch.add_argument("name")
    tuf_fetch.add_argument("version")
    tuf_mirror_options(tuf_fetch, fetching=True)
    tuf_mirror_options(tuf_catalog)
    tuf_fetch.add_argument("--expect")
    tuf_fetch.add_argument("--expect-target", help="require this verified TUF target digest")
    for reader in (tuf_fetch, tuf_catalog):
        reader.add_argument("--expect-snapshot", help="require this verified TUF snapshot digest")
    tuf_catalog.add_argument("--expect-timestamp", help="require this verified TUF timestamp digest")
    tuf_fetch.add_argument("--out", required=True, type=Path)


def registry_commands(commands, snapshot_hours):
    put = commands.add_parser("publish", help="publish a package's source at its exact version")
    put.add_argument("package", type=Path, help="package directory or its witchy.toml")
    put.add_argument("--manifest-pin", help="SHA-384 pin of the absolute, resolved manifest path passed as package")
    put.add_argument("--registry", required=True, help="registry directory")
    put.add_argument("--key", type=Path, help="the owner's witchy-2 key to sign the release with: its 32-byte seed's file (KEY.pub beside it, from `coven key`)")
    put.add_argument("--recovery-key", type=Path, help="with a package's first signed publish: the witchy-2 public key file of the key that alone may hand it to a new owner key")
    put.add_argument("--operator", help="operator key pin for HTTP publication")
    put.add_argument("--registry-id", help="registry identity signed by the operator")
    get = commands.add_parser("fetch", help="copy a published version, verified, into a directory")
    get.add_argument("name")
    get.add_argument("version")
    get.add_argument("--registry", required=True, help="registry directory")
    get.add_argument("--into", required=True, help="directory to receive `package` and source.wy")
    get.add_argument("--expect", help="the locked digest, sha384:<hex>; omitted when resolving")
    get.add_argument("--expect-signer", help="the pinned owner's key ID, witchy-2:<hex>; refuses a package it never owned, or an unsigned one")
    get.add_argument("--expect-recovery", help="the pinned recovery key's key ID, or none")
    get.add_argument("--min-sequence", type=int, default=0, help="the package index sequence already seen; refuses an older index")
    get.add_argument("--operator", help="the pinned registry operator's key ID, witchy-2:<hex>: the snapshot must be signed by it or a key it handed the role to")
    get.add_argument("--registry-id", help="the pinned registry identifier, given with --operator: a snapshot signed for another registry is refused")
    get.add_argument("--snapshot", help="the snapshot to fetch against (one the client kept), instead of the registry's")
    get.add_argument("--min-snapshot", type=int, default=0, help="the snapshot sequence already seen; refuses an older snapshot")
    get.add_argument("--no-snapshot", action="store_true", help="a registry without an operator: only each package's own checks")
    snap = commands.add_parser("snapshot", help="as the registry's operator, sign which index of every package is current")
    snap.add_argument("--registry", required=True)
    snap.add_argument("--key", required=True, help="the operator's key: its 32-byte seed's file (KEY.pub beside it), or fd:N")
    snap.add_argument("--public-key", help="the operator key's public key file (default KEY.pub; required with fd:N)")
    snap.add_argument("--valid-hours", type=int, default=snapshot_hours)
    snap.add_argument("--id", help="with the registry's first snapshot: the registry's identifier, which clients pin with the operator key")
    snap.add_argument("--first", action="store_true", help="the registry's first snapshot (with --id): never inferred from a missing one")
    snap.add_argument("--min-base", type=int, help="the highest snapshot sequence this operator knows it signed (required after the first snapshot); the base must be no older")
    snap.add_argument("--admit", action="append", default=[], metavar="NAME", help="for a served registry: admit this package's first claim, as reviewed (repeat for each)")
    keygen = commands.add_parser("key", aliases=["operator-key"], help="write a witchy-2 key's public key (KEY.pub), from its seed, and print its key ID")
    keygen.add_argument("--key", required=True, help="the 32-byte seed's file (head -c 32 /dev/urandom, mode 600), or fd:N")
    keygen.add_argument("--out", help="where to write the public key (default KEY.pub)")
    check = commands.add_parser("verify-snapshot", help="verify the registry's snapshot against a pinned operator")
    check.add_argument("--registry", required=True)
    check.add_argument("--operator", help="the pinned operator's key ID, witchy-2:<hex> (omitted: trusted on first use, from the registry's first operator)")
    check.add_argument("--registry-id", help="the pinned registry identifier, given with --operator")
    check.add_argument("--min-sequence", type=int, default=0, help="the snapshot sequence already seen")
    check.add_argument("--keep", help="write the verified snapshot's bytes here, for fetch --snapshot")
    catalog = commands.add_parser("catalog", help="read active releases from one verified snapshot")
    catalog.add_argument("--registry", required=True)
    catalog.add_argument("--operator", required=True)
    catalog.add_argument("--registry-id", required=True)
    catalog.add_argument("--min-snapshot", type=int, default=0)


def web_commands(commands):
    web = commands.add_parser("web", help="prepare Coven's first-party web project")
    web_commands = web.add_subparsers(dest="web_command", required=True)
    init = web_commands.add_parser("init", help="create a catalog project with explicit trust")
    init.add_argument("project", type=Path)
    init.add_argument("--registry", required=True)
    init.add_argument("--operator", required=True)
    init.add_argument("--registry-id", required=True)
    init.add_argument("--publisher", required=True, help="the verified Glamour publisher key ID")
    init_tuf = web_commands.add_parser("init-tuf", help="create a catalog project for a signed TUF mirror")
    init_tuf.add_argument("project", type=Path)
    tuf_mirror_options(init_tuf)
    web_check = web_commands.add_parser("check", help="validate a prebuilt generation as the server does")
    web_check.add_argument("generation", type=Path)
    web_install = web_commands.add_parser("install", help="install a verified site into the Witchy HTTPS mirror")
    web_install.add_argument("generation", type=Path)
    web_install.add_argument("--mirror", type=Path, required=True)


def rotation_commands(commands, valid_days, snapshot_hours):
    hand_role = commands.add_parser("rotate-operator", help="hand the registry's operator role to a new key")
    hand_role.add_argument("--registry", required=True)
    hand_role.add_argument("--key", required=True, help="the current operator's key (a seed's file, or fd:N)")
    hand_role.add_argument("--public-key", help="its public key file (default KEY.pub)")
    hand_role.add_argument("--new-key", required=True, help="the new operator's key (a seed's file, or fd:N), which signs the next snapshot")
    hand_role.add_argument("--new-public-key", help="its public key file (default NEW_KEY.pub)")
    hand_role.add_argument("--valid-hours", type=int, default=snapshot_hours)
    hand_role.add_argument("--id", help="the registry's identifier, needed on a machine without the operator's copy of its last snapshot")
    hand_role.add_argument("--min-base", type=int, help="the highest snapshot sequence this operator knows it signed (required); the base must be no older")
    renew = commands.add_parser("refresh", help="re-sign a package's index with a later expiry")
    renew.add_argument("name")
    renew.add_argument("--registry", required=True)
    renew.add_argument("--key", type=Path, required=True, help="the package owner's key (its seed's file)")
    renew.add_argument("--valid-days", type=int, default=valid_days)
    hand = commands.add_parser("rotate", help="hand a package to a new owner key")
    hand.add_argument("name")
    hand.add_argument("--registry", required=True)
    hand.add_argument("--key", type=Path, required=True, help="the package's recovery key, or its owner's key if it has none")
    hand.add_argument("--new-key", type=Path, required=True, help="the new owner's key (its seed's file), which signs the index")
    hand.add_argument("--valid-days", type=int, default=valid_days)
    hand.add_argument("--min-sequence", type=int, default=0, help="the latest index sequence known; required when the recovery key rotates")
    hand.add_argument("--from-index", type=Path, help="for the recovery key: the owner's last copy of the index, to rotate from")
    hand.add_argument("--from-owner", help="for the recovery key: the key ID of the owner it hands the package on from")
    hand.add_argument("--operator", help="for an owner without a recovery key: the pinned operator's key ID; the rotation builds only on the chain its snapshot binds")
    hand.add_argument("--registry-id", help="the pinned registry identifier, given with --operator")
    hand.add_argument("--min-snapshot", type=int, default=0, help="the snapshot sequence already seen; refuses an older snapshot")
    hand.add_argument("--no-snapshot", action="store_true", help="for an owner without a recovery key, in a registry without an operator")
    for state, help in (("yank", "withdraw a version from new locks (locked builds keep it)"),
                        ("revoke", "withdraw a version everywhere, locked builds included")):
        command = commands.add_parser(state, help=help)
        command.add_argument("name")
        command.add_argument("version")
        command.add_argument("--registry", required=True)
        command.add_argument("--reason", required=True, help="one line, shown to every consumer")
        command.add_argument("--key", type=Path, required=True, help="the package owner's key (its seed's file)")


def service_commands(commands):
    tls = commands.add_parser("tls-prepare", help="verify a TLS identity and encode its public certificate chain")
    tls.add_argument("--origin", required=True, help="canonical HTTPS origin")
    tls.add_argument("--fullchain", required=True, type=Path, help="leaf-first PEM chain")
    tls.add_argument("--ca-file", required=True, type=Path, help="independently provisioned PEM trust anchors")
    tls.add_argument("--key", required=True, type=Path, help="private P-384 PKCS#8 DER key")
    tls.add_argument("--out", required=True, type=Path, help="new public chain file")
    tls.add_argument("--module", type=Path, help="prebuilt Witchy TLS identity worker")
    tls.add_argument("--module-pin", help="independent SHA-384 pin for the worker")
    probe = commands.add_parser("mirror-check", help="verify public mirror headers over authenticated HTTPS")
    probe.add_argument("--origin", required=True, help="canonical HTTPS origin")
    probe.add_argument("--route", choices=("timestamp", "catalog"), default="timestamp")
    probe.add_argument("--ca-file", required=True, type=Path, help="independently provisioned PEM roots")
    probe.add_argument("--ca-pin", required=True, help="independent SHA-384 pin for the CA file")
    probe.add_argument("--module", required=True, type=Path, help="prebuilt Witchy mirror check worker")
    probe.add_argument("--module-pin", required=True, help="independent SHA-384 pin for the worker")
    serve = commands.add_parser("serve", help="serve a private registry on a loopback HTTP socket")
    serve.add_argument("--store", required=True, type=Path, help="operator-owned service directory (0700)")
    serve.add_argument("--port", type=int, default=8787, help="loopback port (0 selects a free port)")
    serve.add_argument("--web-dir", type=Path, help="serve a prebuilt Coven Web generation")


def argument_parser(valid_days, snapshot_hours):
    cli = argparse.ArgumentParser(prog="coven")
    commands = cli.add_subparsers(dest="command", required=True)
    package_inputs(commands)
    ci_commands(commands)
    release_commands(commands)
    tuf_commands(commands)
    registry_commands(commands, snapshot_hours)
    web_commands(commands)
    rotation_commands(commands, valid_days, snapshot_hours)
    service_commands(commands)
    return cli
